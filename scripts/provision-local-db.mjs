import pg from 'pg';
import { validateLocalDatabaseUrl } from '../apps/api/dist/config.js';
const urls = ['ADMIN_DATABASE_URL', 'MIGRATION_DATABASE_URL', 'DATABASE_URL'].map(key => {
  if (!process.env[key]) throw new Error(`Missing ${key}`);
  return new URL(validateLocalDatabaseUrl(process.env[key]));
});
const [admin, migration, runtime] = urls;
if (urls.some(url => url.host !== admin.host || url.pathname !== admin.pathname)) throw new Error('All roles must target the same dedicated local database.');
const database = admin.pathname.slice(1);
const migratorName = `${database}_migrator`, runtimeName = `${database}_runtime`;
if (migration.username !== migratorName || runtime.username !== runtimeName || [migratorName, runtimeName].includes(admin.username)) throw new Error('Administrative, migrator and runtime roles must be distinct and use the documented names.');
// Identifiers below are derived only from the two allowlisted database names.
const client = new pg.Client({ connectionString: admin.href });
await client.connect();
try {
  await client.query('BEGIN');
  await client.query("SELECT pg_advisory_xact_lock(731003, 1)");
  for (const [name, url] of [[migratorName, migration], [runtimeName, runtime]]) {
    const existing = await client.query('SELECT rolsuper, rolbypassrls, rolcreaterole, rolcreatedb, rolcanlogin FROM pg_roles WHERE rolname=$1', [name]);
    if (!existing.rowCount) {
      const password = decodeURIComponent(url.password);
      if (!/^[a-f0-9]{48}$/.test(password)) throw new Error('New role passwords must be generated by setup:db-env.');
      await client.query(`CREATE ROLE ${name} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD '${password}'`);
    } else if (Object.entries(existing.rows[0]).some(([key, value]) => key === 'rolcanlogin' ? !value : value)) throw new Error('Existing role has unsafe attributes; manual review required.');
    const memberships = await client.query('SELECT 1 FROM pg_auth_members WHERE member=(SELECT oid FROM pg_roles WHERE rolname=$1)', [name]);
    if (memberships.rowCount) throw new Error('Application roles must not inherit or SET ROLE to other roles.');
  }
  await client.query(`REVOKE ALL ON DATABASE ${database} FROM PUBLIC`);
  await client.query(`GRANT CONNECT ON DATABASE ${database} TO ${migratorName}, ${runtimeName}`);
  await client.query(`GRANT CREATE ON DATABASE ${database} TO ${migratorName}`);
  await client.query('REVOKE CREATE ON SCHEMA public FROM PUBLIC');
  await client.query(`ALTER SCHEMA public OWNER TO ${migratorName}`);
  await client.query(`GRANT USAGE ON SCHEMA public TO ${runtimeName}`);
  await client.query('COMMIT');
  console.log('Dedicated local roles provisioned; no business records created.');
} catch { await client.query('ROLLBACK'); throw new Error('Local provisioning failed. Check dedicated database ownership, role attributes and local configuration; credentials are not logged.'); }
finally { await client.end(); }
